import { markdownToTelegramHtml, RICH_LIMIT, richMarkdown, splitMarkdown, TELEGRAM_LIMIT } from "./format.ts";

interface SendOptions {
  parse_mode?: "HTML";
  message_thread_id?: number;
  reply_parameters?: { message_id: number; allow_sending_without_reply?: boolean };
  link_preview_options?: { is_disabled?: boolean };
}

interface RichMessage {
  markdown: string;
}

/** The Bot API calls the streamer needs; grammY's `bot.api` satisfies this. */
export interface MessageApi {
  sendMessage(chatId: number, text: string, other?: SendOptions): Promise<{ message_id: number }>;
  editMessageText(chatId: number, messageId: number, text: string | RichMessage, other?: SendOptions): Promise<unknown>;
  /** One message for a long answer, up to 32,768 characters, with collapsible blocks (Bot API sendRichMessage). */
  sendRichMessage?(chatId: number, rich: RichMessage, other?: SendOptions): Promise<{ message_id: number }>;
  /** Private chats: a temporary draft bubble while the answer is generated (Bot API sendMessageDraft). */
  sendMessageDraft?(chatId: number, draftId: number, text: string, other?: { can_stop?: boolean }): Promise<unknown>;
}

export interface StreamerOptions {
  replyTo?: number;
  /** Forum topic to post in (omit for normal chats and the General topic). */
  threadId?: number;
  /** Minimum time between preview edits; Telegram rate-limits edits per chat. */
  throttleMs?: number;
  /** Don't send the first preview until this many characters exist (avoids a 1-word ping). */
  minInitialChars?: number;
  /**
   * Private chats: show the answer as a native draft (with Telegram's Stop button)
   * instead of sending and editing a message. The final answer is still sent as messages.
   */
  draftId?: number;
}

const MAX_PREVIEW_FAILURES = 3;
const NO_PREVIEW = { is_disabled: true };

/**
 * Shows a reply while it is generated by sending one message and editing it at
 * most once per `throttleMs` (plain text), then replaces it with the formatted
 * final answer. An answer too long for one message is sent as one rich message (long code
 * collapsed); if Telegram refuses that, it is split into more messages.
 * Works the same in private chats and groups.
 */
export class ReplyStreamer {
  readonly #api: MessageApi;
  readonly #chatId: number;
  readonly #replyTo: number | undefined;
  readonly #threadId: number | undefined;
  readonly #throttleMs: number;
  readonly #minInitialChars: number;
  #messageId: number | undefined;
  #latest = "";
  /** What the bot is doing right now ("🔍 Searching X…"), shown under the text so far. */
  #status = "";
  #shown = "";
  #timer: ReturnType<typeof setTimeout> | undefined;
  #flushing: Promise<void> = Promise.resolve();
  #failures = 0;
  #finished = false;
  /** Telegram said "Too Many Requests": no preview edits before this time. */
  #pausedUntil = 0;
  readonly #draftId: number | undefined;

  constructor(api: MessageApi, chatId: number, options: StreamerOptions = {}) {
    this.#api = api;
    this.#chatId = chatId;
    this.#replyTo = options.replyTo;
    this.#threadId = options.threadId || undefined;
    this.#throttleMs = options.throttleMs ?? 1000;
    this.#minInitialChars = options.minInitialChars ?? 24;
    this.#draftId = options.draftId && this.#api.sendMessageDraft ? options.draftId : undefined;
  }

  /** Drafts: show Telegram's "Thinking…" bubble (with Stop) right away. */
  async start(): Promise<void> {
    if (this.#draftId === undefined) return;
    await this.#api.sendMessageDraft!(this.#chatId, this.#draftId, "", { can_stop: true }).catch(() => this.#failures++);
  }

  /** Whether this reply streams as a draft (so the caller needn't show "typing…"). */
  get usesDraft(): boolean {
    return this.#draftId !== undefined && this.#failures < MAX_PREVIEW_FAILURES;
  }

  /** Report the full text generated so far. Cheap to call on every token. New text ends the status line. */
  update(text: string): void {
    if (text !== this.#latest) this.#status = "";
    this.#latest = text;
    this.#schedule();
  }

  /** Show what the bot is doing ("🔍 Searching X…") until more text arrives; sent even before any text. */
  status(line: string): void {
    this.#status = line;
    this.#schedule();
  }

  #schedule(): void {
    if (this.#finished || this.#timer || this.#failures >= MAX_PREVIEW_FAILURES) return;
    this.#timer = setTimeout(() => {
      this.#timer = undefined;
      this.#flushing = this.#flushing.then(() => this.#flushPreview());
    }, Math.max(this.#throttleMs, this.#pausedUntil - Date.now()));
  }

  /** Replace the preview with the final formatted reply. Returns the ids of all messages used. */
  async finish(markdown: string): Promise<number[]> {
    this.#finished = true;
    clearTimeout(this.#timer);
    this.#timer = undefined;
    await this.#flushing;
    const chunks = splitMarkdown(markdown);
    if (chunks.length === 0) chunks.push("(empty reply)");
    const rich = chunks.length > 1 ? await this.#finishRich(markdown) : undefined;
    if (rich) return rich;
    const ids: number[] = [];
    for (const [index, chunk] of chunks.entries()) {
      const html = markdownToTelegramHtml(chunk);
      if (index === 0 && this.#messageId !== undefined) {
        await this.#editFormatted(this.#messageId, html, chunk);
        ids.push(this.#messageId);
      } else {
        ids.push(await this.#sendFormatted(html, chunk, index === 0 ? this.#replyTo : ids[ids.length - 1]));
      }
    }
    return ids;
  }

  /** The answer as rich messages (one, unless it's over 30,000 characters); undefined if Telegram refuses the first. */
  async #finishRich(markdown: string): Promise<number[] | undefined> {
    if (!this.#api.sendRichMessage) return undefined;
    const ids: number[] = [];
    for (const [index, chunk] of splitMarkdown(markdown, RICH_LIMIT).entries()) {
      const rich = { markdown: richMarkdown(chunk) };
      try {
        if (index === 0 && this.#messageId !== undefined) {
          const messageId = this.#messageId;
          await this.#patient(() => this.#api.editMessageText(this.#chatId, messageId, rich));
          ids.push(messageId);
        } else {
          const other = this.#sendOptions(index === 0 ? this.#replyTo : ids.at(-1));
          delete other.link_preview_options;
          const sent = await this.#patient(() => this.#api.sendRichMessage!(this.#chatId, rich, other));
          ids.push(sent.message_id);
        }
      } catch (error) {
        // Not available or not accepted: the usual messages instead (they edit the preview too).
        if (index === 0 && retryAfter(error) === undefined) return undefined;
        throw error;
      }
    }
    return ids;
  }

  /** End with a plain error notice instead of a reply. Returns the ids of the messages used. */
  async fail(notice: string): Promise<number[]> {
    this.#finished = true;
    clearTimeout(this.#timer);
    await this.#flushing;
    const partial = this.#latest.trim();
    const text = partial ? `${partial}\n\n⚠️ ${notice}` : `⚠️ ${notice}`;
    return this.finish(text);
  }

  async #flushPreview(): Promise<void> {
    if (this.#finished) return;
    const preview = previewText([this.#latest.trim(), this.#status].filter(Boolean).join("\n\n"));
    if (this.#draftId !== undefined) {
      if (!preview || preview === this.#shown) return;
      try {
        await this.#api.sendMessageDraft!(this.#chatId, this.#draftId, preview, { can_stop: true });
        this.#shown = preview;
        this.#failures = 0;
      } catch {
        this.#failures++;
      }
      return;
    }
    if (this.#messageId === undefined && !this.#status && this.#latest.trim().length < this.#minInitialChars) return;
    if (!preview || preview === this.#shown) return;
    try {
      if (this.#messageId === undefined) {
        const sent = await this.#api.sendMessage(this.#chatId, preview, this.#sendOptions(this.#replyTo));
        this.#messageId = sent.message_id;
      } else {
        await this.#api.editMessageText(this.#chatId, this.#messageId, preview, { link_preview_options: NO_PREVIEW });
      }
      this.#shown = preview;
      this.#failures = 0;
    } catch (error) {
      const wait = retryAfter(error);
      if (wait !== undefined) this.#pausedUntil = Date.now() + wait * 1000;
      else if (!isNotModified(error)) this.#failures++;
    }
  }

  async #sendFormatted(html: string, plain: string, replyTo: number | undefined): Promise<number> {
    return this.#patient(() => this.#sendFormattedOnce(html, plain, replyTo));
  }

  async #editFormatted(messageId: number, html: string, plain: string): Promise<void> {
    return this.#patient(() => this.#editFormattedOnce(messageId, html, plain));
  }

  /** The final answer must arrive: after "Too Many Requests", wait as long as Telegram says (up to a minute) and try again. */
  async #patient<T>(call: () => Promise<T>): Promise<T> {
    for (let attempt = 0; ; attempt++) {
      try {
        return await call();
      } catch (error) {
        const wait = retryAfter(error);
        if (wait === undefined || wait > 60 || attempt >= 2) throw error;
        await new Promise((resolve) => setTimeout(resolve, (wait + 1) * 1000));
      }
    }
  }

  async #sendFormattedOnce(html: string, plain: string, replyTo: number | undefined): Promise<number> {
    try {
      const sent = await this.#api.sendMessage(this.#chatId, html, { ...this.#sendOptions(replyTo), parse_mode: "HTML" });
      return sent.message_id;
    } catch (error) {
      if (!isParseError(error)) throw error;
      const sent = await this.#api.sendMessage(this.#chatId, plain.slice(0, TELEGRAM_LIMIT), this.#sendOptions(replyTo));
      return sent.message_id;
    }
  }

  async #editFormattedOnce(messageId: number, html: string, plain: string): Promise<void> {
    try {
      await this.#api.editMessageText(this.#chatId, messageId, html, { parse_mode: "HTML", link_preview_options: NO_PREVIEW });
    } catch (error) {
      if (isNotModified(error)) return;
      if (!isParseError(error)) throw error;
      try {
        await this.#api.editMessageText(this.#chatId, messageId, plain.slice(0, TELEGRAM_LIMIT), {
          link_preview_options: NO_PREVIEW,
        });
      } catch (fallbackError) {
        if (!isNotModified(fallbackError)) throw fallbackError;
      }
    }
  }

  #sendOptions(replyTo: number | undefined): SendOptions {
    return {
      link_preview_options: NO_PREVIEW,
      ...(this.#threadId !== undefined ? { message_thread_id: this.#threadId } : {}),
      ...(replyTo !== undefined ? { reply_parameters: { message_id: replyTo, allow_sending_without_reply: true } } : {}),
    };
  }
}

/** The status line for a tool step: ours (read_link…) or Grok's server-side search (x_keyword_search, web_search…). */
export function activityLine(tool: string): string {
  if (/^x_|twitter/i.test(tool)) return "🔍 Searching X…";
  if (/search|browse/i.test(tool)) return "🔍 Searching the web…";
  if (tool === "read_link") return "📖 Reading the link…";
  if (tool === "read_group_chat") return "💬 Reading the chat…";
  if (tool === "watch_video") return "🎬 Watching the video…";
  if (tool === "create_image") return "🎨 Drawing…";
  if (tool === "create_poll") return "📊 Making the poll…";
  if (tool === "remember") return "📝 Noting it down…";
  return "⚙️ Working on it…";
}

/** Plain-text preview that always fits in one Telegram message. */
export function previewText(text: string): string {
  const trimmed = text.trim();
  return trimmed.length > TELEGRAM_LIMIT - 2 ? `${trimmed.slice(0, TELEGRAM_LIMIT - 2)} …` : trimmed;
}

function description(error: unknown): string {
  const value = (error as { description?: unknown; message?: unknown } | null) ?? {};
  return String(value.description ?? value.message ?? "");
}

/** Seconds Telegram asks to wait after "429 Too Many Requests"; undefined for other errors. */
function retryAfter(error: unknown): number | undefined {
  const value = error as { error_code?: number; parameters?: { retry_after?: number } } | null;
  if (value?.error_code !== 429 && !/too many requests/i.test(description(error))) return undefined;
  return value?.parameters?.retry_after ?? Number(description(error).match(/retry after (\d+)/i)?.[1] ?? 5);
}

function isNotModified(error: unknown): boolean {
  return /message is not modified/i.test(description(error));
}

function isParseError(error: unknown): boolean {
  return /can't parse entities|unsupported start tag|can't find end tag/i.test(description(error));
}
